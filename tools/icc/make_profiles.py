"""Write the color profiles CloakFrame attaches to outputs whose pixels stay in sRGB, Display P3 or
Adobe RGB (1998) (plan D2).

Usage: python -I tools/icc/make_profiles.py <assets/icc dir>

ICC v2.1 display profiles (matrix/TRC) built from the published primaries, white point and tone
curve of each space, with colorants Bradford-adapted to the D50 PCS. This is the construction of
tools/fixture-extract/gen_inputs.py, under the names applications show. The output is byte for
byte deterministic; a change here changes the files committed in assets/icc.
"""

import struct
import sys
from pathlib import Path

D50 = (0.9642, 1.0, 0.8249)
BRADFORD = ((0.8951, 0.2664, -0.1614), (-0.7502, 1.7135, 0.0367), (0.0389, -0.0685, 1.0296))

PROFILES = {
    "srgb.icc": ("sRGB IEC61966-2.1", ((0.64, 0.33), (0.30, 0.60), (0.15, 0.06)), "srgb"),
    "display-p3.icc": ("Display P3", ((0.680, 0.320), (0.265, 0.690), (0.150, 0.060)), "srgb"),
    "adobe-rgb.icc": (
        "Adobe RGB (1998) compatible",
        ((0.64, 0.33), (0.21, 0.71), (0.15, 0.06)),
        563 / 256,
    ),
}
D65_XY = (0.3127, 0.3290)


def matmul(a, b):
    return tuple(tuple(sum(a[i][k] * b[k][j] for k in range(3)) for j in range(3)) for i in range(3))


def matvec(a, v):
    return tuple(sum(a[i][k] * v[k] for k in range(3)) for i in range(3))


def inverse(m):
    (a, b, c), (d, e, f), (g, h, i) = m
    det = a * (e * i - f * h) - b * (d * i - f * g) + c * (d * h - e * g)
    return (
        ((e * i - f * h) / det, (c * h - b * i) / det, (b * f - c * e) / det),
        ((f * g - d * i) / det, (a * i - c * g) / det, (c * d - a * f) / det),
        ((d * h - e * g) / det, (b * g - a * h) / det, (a * e - b * d) / det),
    )


def xy_to_xyz(x, y):
    return (x / y, 1.0, (1 - x - y) / y)


def rgb_to_xyz(primaries, white):
    cols = [xy_to_xyz(*p) for p in primaries]
    m = tuple(tuple(cols[j][i] for j in range(3)) for i in range(3))
    scale = matvec(inverse(m), white)
    return tuple(tuple(m[i][j] * scale[j] for j in range(3)) for i in range(3))


def adapt(white_from, white_to):
    src, dst = matvec(BRADFORD, white_from), matvec(BRADFORD, white_to)
    diag = tuple(tuple(dst[i] / src[i] if i == j else 0.0 for j in range(3)) for i in range(3))
    return matmul(matmul(inverse(BRADFORD), diag), BRADFORD)


def s15f16(v):
    return struct.pack(">i", round(v * 65536))


def xyz_tag(xyz):
    return b"XYZ " + b"\0" * 4 + b"".join(s15f16(c) for c in xyz)


def desc_tag(text):
    ascii_bytes = text.encode("ascii") + b"\0"
    return (
        b"desc" + b"\0" * 4 + struct.pack(">I", len(ascii_bytes)) + ascii_bytes
        + b"\0" * 8 + b"\0" * 3 + b"\0" * 67
    )


def text_tag(text):
    return b"text" + b"\0" * 4 + text.encode("ascii") + b"\0"


def curve_tag(trc):
    if trc != "srgb":
        return b"curv" + b"\0" * 4 + struct.pack(">IH", 1, round(trc * 256))
    # ICC v2 has no parametric curves; the sRGB curve is sampled.
    n = 1024
    values = b""
    for i in range(n):
        x = i / (n - 1)
        y = x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4
        values += struct.pack(">H", min(65535, max(0, round(y * 65535))))
    return b"curv" + b"\0" * 4 + struct.pack(">I", n) + values


def profile(name, primaries, trc):
    white = xy_to_xyz(*D65_XY)
    m = matmul(adapt(white, D50), rgb_to_xyz(primaries, white))
    curve = curve_tag(trc)
    tags = [
        (b"desc", desc_tag(name)),
        (b"cprt", text_tag("No copyright. Generated by CloakFrame from the published primaries.")),
        (b"wtpt", xyz_tag(white)),
        (b"rXYZ", xyz_tag([m[i][0] for i in range(3)])),
        (b"gXYZ", xyz_tag([m[i][1] for i in range(3)])),
        (b"bXYZ", xyz_tag([m[i][2] for i in range(3)])),
        (b"rTRC", curve), (b"gTRC", curve), (b"bTRC", curve),
    ]
    offset = 128 + 4 + 12 * len(tags)
    table, data, shared = struct.pack(">I", len(tags)), b"", {}
    for sig, payload in tags:
        if payload not in shared:
            data += b"\0" * (-(offset + len(data)) % 4)
            shared[payload] = (offset + len(data), len(payload))
            data += payload
        table += sig + struct.pack(">II", *shared[payload])
    data += b"\0" * (-(offset + len(data)) % 4)
    header = (
        struct.pack(">I", offset + len(data)) + b"\0" * 4 + struct.pack(">I", 0x02100000)
        + b"mntrRGB XYZ " + struct.pack(">6H", 2026, 10, 18, 0, 0, 0) + b"acsp"
        + b"\0" * 28 + b"".join(s15f16(c) for c in D50) + b"\0" * 48
    )
    assert len(header) == 128
    return header + table + data


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    for file, (name, primaries, trc) in PROFILES.items():
        (out / file).write_bytes(profile(name, primaries, trc))


if __name__ == "__main__":
    main()
