"""Generate the synthetic inputs the fixtures use.

Usage: python3 -I gen_inputs.py <fixtures dir> <astronaut.png>

Everything here is derived from formulas or from astronaut.png (NASA, public domain), so the
generated files can live in the repository. Videos depend on the local FFmpeg/x264 build, which
is why the files themselves are committed and the recipes are recorded next to them.
"""

import json
import struct
import subprocess
import sys
import wave
from pathlib import Path

import numpy as np
from PIL import Image

D50 = np.array([0.9642, 1.0, 0.8249])
D65 = np.array([0.95047, 1.0, 1.08883])
BRADFORD = np.array(
    [[0.8951, 0.2664, -0.1614], [-0.7502, 1.7135, 0.0367], [0.0389, -0.0685, 1.0296]]
)


def xy_to_xyz(x, y):
    return np.array([x / y, 1.0, (1 - x - y) / y])


def rgb_to_xyz_matrix(primaries, white):
    cols = np.stack([xy_to_xyz(*p) for p in primaries], axis=1)
    scale = np.linalg.solve(cols, white)
    return cols * scale


def adapt(white_from, white_to):
    src = BRADFORD @ white_from
    dst = BRADFORD @ white_to
    return np.linalg.inv(BRADFORD) @ np.diag(dst / src) @ BRADFORD


def s15f16(v):
    return struct.pack(">i", int(round(v * 65536)))


def xyz_tag(xyz):
    return b"XYZ " + b"\0" * 4 + b"".join(s15f16(c) for c in xyz)


def desc_tag(text):
    ascii_bytes = text.encode("ascii") + b"\0"
    return (
        b"desc"
        + b"\0" * 4
        + struct.pack(">I", len(ascii_bytes))
        + ascii_bytes
        + b"\0" * 4  # unicode language code
        + b"\0" * 4  # unicode count
        + b"\0" * 2  # scriptcode code
        + b"\0"  # scriptcode count
        + b"\0" * 67
    )


def text_tag(text):
    return b"text" + b"\0" * 4 + text.encode("ascii") + b"\0"


def curve_tag(trc):
    if trc[0] == "gamma":
        return b"curv" + b"\0" * 4 + struct.pack(">I", 1) + struct.pack(">H", int(round(trc[1] * 256)))
    # sRGB piecewise curve, sampled as ICC v2 cannot carry parametric curves.
    n = 1024
    x = np.linspace(0, 1, n)
    y = np.where(x <= 0.04045, x / 12.92, ((x + 0.055) / 1.055) ** 2.4)
    values = np.clip(np.round(y * 65535), 0, 65535).astype(">u2").tobytes()
    return b"curv" + b"\0" * 4 + struct.pack(">I", n) + values


def icc_profile(name, primaries, white, trc):
    """ICC v2.1 display profile (matrix/TRC), colorants Bradford-adapted to the D50 PCS."""
    matrix = adapt(white, D50) @ rgb_to_xyz_matrix(primaries, white)
    tags = [
        (b"desc", desc_tag(name)),
        (b"cprt", text_tag("No copyright, generated by CloakFrame fixture tools")),
        (b"wtpt", xyz_tag(white)),
        (b"rXYZ", xyz_tag(matrix[:, 0])),
        (b"gXYZ", xyz_tag(matrix[:, 1])),
        (b"bXYZ", xyz_tag(matrix[:, 2])),
    ]
    curve = curve_tag(trc)
    tags += [(b"rTRC", curve), (b"gTRC", curve), (b"bTRC", curve)]

    table_size = 4 + 12 * len(tags)
    offset = 128 + table_size
    table = struct.pack(">I", len(tags))
    data = b""
    shared = {}
    for sig, payload in tags:
        if payload in shared:
            table += sig + struct.pack(">II", *shared[payload])
            continue
        while (offset + len(data)) % 4:
            data += b"\0"
        start = offset + len(data)
        shared[payload] = (start, len(payload))
        table += sig + struct.pack(">II", start, len(payload))
        data += payload
    while (offset + len(data)) % 4:
        data += b"\0"
    size = offset + len(data)
    header = (
        struct.pack(">I", size)
        + b"\0" * 4
        + struct.pack(">I", 0x02100000)
        + b"mntrRGB XYZ "
        + struct.pack(">6H", 2026, 10, 16, 0, 0, 0)
        + b"acsp"
        + b"\0" * 24  # platform, flags, manufacturer, model, attributes
        + b"\0" * 4  # rendering intent: perceptual
        + b"".join(s15f16(c) for c in D50)
        + b"\0" * 4
        + b"\0" * 16
        + b"\0" * 28
    )
    assert len(header) == 128
    return header + table + data


PROFILES = {
    "display-p3": ("Display P3 (CloakFrame fixture)", [(0.680, 0.320), (0.265, 0.690), (0.150, 0.060)], D65, ("srgb",)),
    "adobe-rgb": ("Adobe RGB (1998) compatible (CloakFrame fixture)", [(0.640, 0.330), (0.210, 0.710), (0.150, 0.060)], D65, ("gamma", 563 / 256)),
    "srgb": ("sRGB (CloakFrame fixture)", [(0.640, 0.330), (0.300, 0.600), (0.150, 0.060)], D65, ("srgb",)),
    "wide-gamma18": ("Wide gamut gamma 1.8 D50 (CloakFrame fixture)", [(0.7347, 0.2653), (0.1596, 0.8404), (0.0366, 0.0001)], D50, ("gamma", 1.8)),
}


def color_chart(width=256, height=192):
    """Saturated patches plus a gray ramp: wide-gamut tagging changes these visibly."""
    image = np.zeros((height, width, 3), np.uint8)
    # Mid-saturation colours stay inside sRGB after conversion, so a wrong conversion shows
    # as a value change instead of being hidden by clipping.
    patches = [
        (180, 60, 50), (60, 170, 80), (50, 80, 190), (190, 180, 60),
        (70, 170, 170), (170, 70, 170), (200, 120, 80), (120, 90, 60),
    ]
    pw = width // 4
    ph = height // 3
    for i, color in enumerate(patches):
        x, y = (i % 4) * pw, (i // 4) * ph
        image[y : y + ph, x : x + pw] = color
    ramp = np.linspace(0, 255, width).astype(np.uint8)
    image[2 * ph :, :, :] = ramp[None, :, None]
    return image


def gen_icc(root: Path):
    out = root / "defects" / "D2"
    out.mkdir(parents=True, exist_ok=True)
    chart = Image.fromarray(color_chart())
    cases = []
    for key, (name, primaries, white, trc) in PROFILES.items():
        profile = icc_profile(name, primaries, white, trc)
        (out / f"{key}.icc").write_bytes(profile)
        for ext, kwargs in [("png", {}), ("jpg", {"quality": 95, "subsampling": 0})]:
            path = out / f"chart-{key}.{ext}"
            chart.save(path, icc_profile=profile, **kwargs)
            cases.append(path.name)
    # References converted by Little CMS (relative colorimetric): the "other profile" case, and
    # Display P3 and Adobe RGB written to BMP, which carries no profile.
    gen_srgb_references(out, chart)
    # The same pixels with no profile at all: treated as sRGB, nothing to attach.
    chart.save(out / "chart-untagged.png")
    cases.append("chart-untagged.png")
    return cases


def gen_srgb_references(out: Path, chart):
    from PIL import ImageCms
    import io

    srgb = ImageCms.ImageCmsProfile(io.BytesIO((out / "srgb.icc").read_bytes()))
    for key in ["wide-gamma18", "display-p3", "adobe-rgb"]:
        source = ImageCms.ImageCmsProfile(io.BytesIO((out / f"{key}.icc").read_bytes()))
        converted = ImageCms.profileToProfile(
            chart, source, srgb, renderingIntent=ImageCms.Intent.RELATIVE_COLORIMETRIC, outputMode="RGB"
        )
        converted.save(out / f"expected-{key}-as-srgb.png")


def gen_mosaic(root: Path):
    out = root / "defects" / "D3"
    out.mkdir(parents=True, exist_ok=True)
    # Gradients give every mosaic cell a different mean while compressing well.
    y, x = np.mgrid[0:600, 0:600]
    image = np.full((800, 800, 3), 128, np.uint8)
    image[100:700, 100:700, 0] = (x * 255 // 599).astype(np.uint8)
    image[100:700, 100:700, 1] = (y * 255 // 599).astype(np.uint8)
    image[100:700, 100:700, 2] = ((x + y) * 255 // 1198).astype(np.uint8)
    Image.fromarray(image).save(out / "noise-face-600.png")


def gen_encoding(root: Path, astronaut: Path):
    out = root / "defects" / "D6"
    out.mkdir(parents=True, exist_ok=True)
    base = Image.open(astronaut).convert("RGB")
    big = base.resize((1024, 1024), Image.Resampling.LANCZOS)
    lossy = {
        "q90-420.jpg": {"quality": 90, "subsampling": 2},
        "q85-422.jpg": {"quality": 85, "subsampling": 1},
        "q95-444.jpg": {"quality": 95, "subsampling": 0},
        "lossy-q75.webp": {"quality": 75, "lossless": False},
    }
    for name, kwargs in lossy.items():
        big.save(out / name, **kwargs)
    lossless = {
        "lossless.webp": {"lossless": True},
        "lossless.png": {},
        "lossless.tif": {"compression": "tiff_deflate"},
    }
    for name, kwargs in lossless.items():
        base.save(out / name, **kwargs)


def gen_detect(root: Path, astronaut: Path):
    out = root / "detect" / "inputs"
    out.mkdir(parents=True, exist_ok=True)
    src = Image.open(astronaut).convert("RGB")

    canvas = Image.new("RGB", (1920, 1080), (96, 96, 96))
    x = 16
    for scale in [1.0, 0.5, 0.25, 0.125, 0.0625]:
        size = max(1, int(round(512 * scale)))
        canvas.paste(src.resize((size, size), Image.Resampling.LANCZOS), (x, 16))
        x += size + 16
    canvas.save(out / "astronaut-scales.png")

    face = src.crop((170, 40, 280, 190))
    crowd = Image.new("RGB", (640, 640), (96, 96, 96))
    tile = face.resize((32, 44), Image.Resampling.LANCZOS)
    for row in range(14):
        for col in range(20):
            crowd.paste(tile, (col * 32, row * 45 + 4))
    crowd.save(out / "crowd-280-faces.png")


def frame_index_frame(index, width, height, rng_square=True):
    """Gray frame whose top rows carry the 16-bit frame index as black/white blocks."""
    frame = np.full((height, width, 3), 128, np.uint8)
    block = max(8, min(width, height) // 12)
    for bit in range(16):
        on = (index >> bit) & 1
        bx = (bit % 8) * block
        by = (bit // 8) * block
        frame[by : by + block, bx : bx + block] = 235 if on else 16
    if rng_square:
        size = max(8, height // 6)
        x = (index * 7) % max(1, width - size)
        y = height // 2
        frame[y : y + size, x : x + size] = (40, 90, 200)
    return frame


def decode_frame_index(frame):
    height, width = frame.shape[:2]
    block = max(8, min(width, height) // 12)
    gray = frame.mean(axis=2) if frame.ndim == 3 else frame
    value = 0
    for bit in range(16):
        bx = (bit % 8) * block + block // 2
        by = (bit // 8) * block + block // 2
        if gray[by, bx] > 128:
            value |= 1 << bit
    return value


def write_wav_with_clicks(path: Path, seconds, rate=48000, period=0.5, offset=0.0):
    samples = np.zeros(int(round(seconds * rate)), np.int16)
    t = offset
    while t < seconds:
        start = int(round(t * rate))
        samples[start : start + 48] = 20000
        t += period
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(samples.tobytes())


def encode_frames(path: Path, frames, fps, extra_input=(), extra_args=(), pre_args=()):
    height, width = frames[0].shape[:2]
    cmd = [
        "ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
        *pre_args,
        "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{width}x{height}", "-r", fps, "-i", "-",
        *extra_input,
        *extra_args,
        str(path),
    ]
    proc = subprocess.Popen(cmd, stdin=subprocess.PIPE)
    for frame in frames:
        proc.stdin.write(frame.tobytes())
    proc.stdin.close()
    if proc.wait() != 0:
        raise SystemExit(f"ffmpeg failed for {path}")
    return cmd


def run(cmd):
    subprocess.run(cmd, check=True)
    return cmd


def gen_video(root: Path, scratch: Path):
    recipes = {}
    d1 = root / "defects" / "D1"
    d1.mkdir(parents=True, exist_ok=True)
    common = ["-hide_banner", "-loglevel", "error", "-y"]
    for name, size, matrix, rng, tags in [
        ("bt709-tv-1080p.mp4", "1920x1080", "bt709", "tv", ["bt709", "bt709", "bt709", "tv"]),
        ("bt709-pc-1080p.mp4", "1920x1080", "bt709", "pc", ["bt709", "bt709", "bt709", "pc"]),
        ("bt601-tv-480p.mp4", "720x480", "smpte170m", "tv", ["smpte170m", "smpte170m", "smpte170m", "tv"]),
    ]:
        cmd = [
            "ffmpeg", *common,
            "-f", "lavfi", "-i", f"color=c=0xC83C28:s={size}:r=30:d=0.5",
            # The colour source must be RGB, or lavfi negotiates YUV directly with its own matrix.
            "-vf", (
                f"format=rgb24,scale=out_color_matrix={matrix}:out_range={rng},format=yuv420p,"
                f"setparams=colorspace={tags[0]}:color_primaries={tags[1]}:color_trc={tags[2]}:range={tags[3]}"
            ),
            "-c:v", "libx264", "-crf", "12",
            "-colorspace", tags[0], "-color_primaries", tags[1], "-color_trc", tags[2], "-color_range", tags[3],
            str(d1 / name),
        ]
        recipes[f"defects/D1/{name}"] = run(cmd)

    p3 = root / "defects" / "P-3"
    p3.mkdir(parents=True, exist_ok=True)
    frames = [frame_index_frame(i, 640, 360) for i in range(90)]
    recipes["defects/P-3/cfr-2997-offset-bframes.mp4"] = encode_frames(
        p3 / "cfr-2997-offset-bframes.mp4", frames, "30000/1001",
        extra_args=["-c:v", "libx264", "-bf", "3", "-g", "24", "-pix_fmt", "yuv420p", "-output_ts_offset", "1.25"],
    )
    recipes["defects/P-3/cfr-23976.mp4"] = encode_frames(
        p3 / "cfr-23976.mp4", frames[:72], "24000/1001",
        extra_args=["-c:v", "libx264", "-bf", "2", "-pix_fmt", "yuv420p"],
    )
    vfr_source = scratch / "vfr-source.mp4"
    encode_frames(vfr_source, frames[:60], "30", extra_args=["-c:v", "libx264", "-pix_fmt", "yuv420p"])
    # First 30 frames at 30 fps, the rest at 15 fps: a real VFR timeline without dropped frames.
    recipes["defects/P-3/vfr-30-15.mp4"] = run([
        "ffmpeg", *common, "-i", str(vfr_source),
        "-vf", "setpts='if(lt(N,30),N/30/TB,(1+(N-30)/15)/TB)'",
        "-fps_mode", "passthrough", "-c:v", "libx264", "-pix_fmt", "yuv420p",
        str(p3 / "vfr-30-15.mp4"),
    ])
    recipes["defects/P-3/rotated-90.mp4"] = run([
        "ffmpeg", *common, "-display_rotation", "90", "-i", str(p3 / "cfr-23976.mp4"),
        "-c", "copy", str(p3 / "rotated-90.mp4"),
    ])

    p5 = root / "defects" / "P-5"
    p5.mkdir(parents=True, exist_ok=True)
    odd = [frame_index_frame(i, 641, 361) for i in range(60)]
    wav = scratch / "clicks-3s.wav"
    write_wav_with_clicks(wav, 3.0)
    recipes["defects/P-5/odd-641x361-audio-longer.mp4"] = encode_frames(
        p5 / "odd-641x361-audio-longer.mp4", odd, "30",
        extra_input=["-i", str(wav)],
        extra_args=["-map", "0:v", "-map", "1:a", "-c:v", "libx264", "-pix_fmt", "yuv444p",
                    "-c:a", "aac", "-b:a", "128k"],
    )
    wav_early = scratch / "clicks-2.4s.wav"
    write_wav_with_clicks(wav_early, 2.4)
    video_only = scratch / "late-video.mp4"
    encode_frames(video_only, [frame_index_frame(i, 640, 360) for i in range(60)], "30",
                  extra_args=["-c:v", "libx264", "-pix_fmt", "yuv420p"])
    # Video starts 0.4 s after the audio, as when a phone starts recording sound first.
    recipes["defects/P-5/audio-starts-early.mp4"] = run([
        "ffmpeg", *common, "-itsoffset", "0.4", "-i", str(video_only), "-i", str(wav_early),
        "-map", "0:v", "-map", "1:a", "-c:v", "copy", "-c:a", "aac", "-b:a", "128k",
        str(p5 / "audio-starts-early.mp4"),
    ])
    return recipes


def main():
    root = Path(sys.argv[1])
    astronaut = Path(sys.argv[2])
    scratch = Path(sys.argv[3])
    scratch.mkdir(parents=True, exist_ok=True)
    gen_icc(root)
    gen_mosaic(root)
    gen_encoding(root, astronaut)
    gen_detect(root, astronaut)
    recipes = gen_video(root, scratch)
    version = subprocess.run(["ffmpeg", "-version"], capture_output=True, text=True).stdout.splitlines()[0]
    (root / "generated-media.json").write_text(
        json.dumps({"ffmpeg": version, "pillow": Image.__version__, "numpy": np.__version__, "recipes": recipes}, indent=2) + "\n"
    )


if __name__ == "__main__":
    main()
