/// A plain lowercase ISO 639 code as its three-letter form; `und` and anything else is dropped.
pub fn mp4_language(tag: &str) -> Option<String> {
    if !tag.bytes().all(|b| b.is_ascii_lowercase()) {
        return None;
    }
    match tag.len() {
        3 if tag != "und" => Some(tag.to_owned()),
        2 => ISO_639_1_TO_2T
            .binary_search_by_key(&tag, |&(two, _)| two)
            .ok()
            .map(|i| ISO_639_1_TO_2T[i].1.to_owned()),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_sorted_and_each_code_is_well_formed() {
        assert!(ISO_639_1_TO_2T.windows(2).all(|w| w[0].0 < w[1].0));
        for (two, three) in ISO_639_1_TO_2T {
            assert!(two.len() == 2 && three.len() == 3, "{two} {three}");
            assert!(
                (two.to_owned() + three)
                    .bytes()
                    .all(|b| b.is_ascii_lowercase())
            );
        }
    }

    #[test]
    fn two_letter_codes_become_the_terminology_form() {
        let cases = [
            ("en", Some("eng")),
            ("de", Some("deu")),
            ("fr", Some("fra")),
            ("zh", Some("zho")),
            ("ko", Some("kor")),
            ("ger", Some("ger")),
            ("qaa", Some("qaa")),
            ("zz", None),
            ("und", None),
            ("EN", None),
            ("en-US", None),
            ("e", None),
        ];
        for (tag, expected) in cases {
            assert_eq!(mp4_language(tag).as_deref(), expected, "{tag}");
        }
    }
}
